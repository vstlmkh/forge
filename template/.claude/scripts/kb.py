def validate(root: str, notes: list[Note], arts: list[agile.Artifact]) -> list[agile.Issue]:
    issues: list[agile.Issue] = []
    SCOPES = kb_scopes(root)
    LOCKED = scope_locked(root)

    def err(n, field, msg):
        issues.append(agile.Issue(n.rel, field, msg))

    def warn(n, field, msg):
        issues.append(agile.Issue(n.rel, field, msg, "WARN"))

    ticket_ids = {a.id for a in arts if a.id}
    by_base: dict[str, Note] = {}
    for n in notes:
        if n.base in by_base:
            err(n, "filename", f"duplicate basename, also used by {by_base[n.base].rel}")
        else:
            by_base[n.base] = n

    rel_kb = forgecfg.load(root).kb_rel
    for n in notes:
        # ---- location -----------------------------------------------------
        if n.dir_scope is None:
            err(n, "path", f"a note lives at {rel_kb}/<scope>/<type>/<file>.md, never higher")
            continue
        if n.dir_scope not in SCOPES:
            err(n, "path", f"'{n.dir_scope}' is not one of {SCOPES}")
        if n.dir_type not in TYPES:
            err(n, "path", f"'{n.dir_type}' is not a known type, expected one of {sorted(TYPES)}")

        # ---- filename -----------------------------------------------------
        m = NAME_RE.match(n.base)
        if not m:
            err(n, "filename",
                "must be '{<type>} <description> - <yyyy-mm-dd>.md' - the braces around "
                "the type are literal, and the date follows a ' - ' separator")
        else:
            ftype, desc, fdate = m.group("type"), m.group("desc"), m.group("date")
            if ftype not in TYPES:
                err(n, "filename", f"'{ftype}' is not a known type, expected one of {sorted(TYPES)}")
            elif n.dir_type in TYPES and ftype != n.dir_type:
                err(n, "filename", f"'{{{ftype}}}' contradicts the folder '{n.dir_type}'")
            if not DESC_RE.match(desc):
                err(n, "filename", f"description '{desc}' must be lowercase words separated by spaces")
            if n.fm.get("created") and str(n.fm["created"]) != fdate:
                err(n, "created", f"'{n.fm['created']}' contradicts the date in the filename ({fdate})")
        if len(os.path.basename(n.rel)) > MAX_BASENAME:
            err(n, "filename", f"{len(os.path.basename(n.rel))} chars, the limit is {MAX_BASENAME}")

        # ---- frontmatter --------------------------------------------------
        for f in REQUIRED_FIELDS:
            if f not in n.fm:
                err(n, f, "field is missing")

        ntype = n.fm.get("type")
        if ntype not in TYPES:
            err(n, "type", f"'{ntype}' is not one of {sorted(TYPES)}")
        elif n.dir_type in TYPES and ntype != n.dir_type:
            err(n, "type", f"'{ntype}' contradicts the folder '{n.dir_type}'")

        nscope = n.fm.get("scope")
        if nscope not in SCOPES:
            err(n, "scope", f"'{nscope}' is not one of {SCOPES}")
        elif n.dir_scope in SCOPES and nscope != n.dir_scope:
            err(n, "scope", f"'{nscope}' contradicts the folder '{n.dir_scope}'")

        if ntype in LOCKED and nscope not in LOCKED[ntype]:
            err(n, "scope", f"type '{ntype}' may only live in {sorted(LOCKED[ntype])}")

        if not n.title:
            err(n, "title", "must not be empty")
        elif len(n.title) < 12:
            warn(n, "title", "state the finding as a sentence, not a one-word label")

        if n.status not in NOTE_STATUSES:
            err(n, "status", f"'{n.status}' is not one of {NOTE_STATUSES}")

        for f in ("created", "updated"):
            v = n.fm.get(f)
            if v is None:
                err(n, f, "must be a date")
            elif not DATE_RE.match(str(v)):
                err(n, f, f"'{v}' is not YYYY-MM-DD")
        cre, upd = str(n.fm.get("created")), str(n.fm.get("updated"))
        if DATE_RE.match(cre) and DATE_RE.match(upd) and upd < cre:
            err(n, "updated", f"'{upd}' precedes created '{cre}'")

        # ---- tickets ------------------------------------------------------
        tickets = n.listfield("tickets")
        if not tickets:
            warn(n, "tickets", "no ticket recorded - which work produced or confirmed this?")
        for t in tickets:
            if t not in ticket_ids:
                err(n, "tickets", f"'{t}' does not resolve to an artifact in the tracker")

        # ---- supersession -------------------------------------------------
        sb = n.fm.get("superseded_by")
        if n.status == "superseded":
            if not sb:
                err(n, "superseded_by", "a superseded note must point at its replacement")
            elif not resolve(notes, str(sb)):
                err(n, "superseded_by", f"'{sb}' does not resolve to a note")
        elif sb:
            err(n, "superseded_by", "set only when status is 'superseded'")

        # ---- body ---------------------------------------------------------
        for heading in TYPES.get(ntype, []) if ntype in TYPES else []:
            if not re.search(r"^##\s+" + re.escape(heading) + r"\s*$", n.body, re.MULTILINE):
                err(n, "body", f"missing section '## {heading}'")
            elif not n.has_section(heading):
                err(n, "body", f"section '## {heading}' is empty or a placeholder")
        if not re.search(r"^##\s+Related\s*$", n.body, re.MULTILINE):
            err(n, "body", "missing section '## Related' - keep it with '- _none yet_' if empty")

        # ---- links --------------------------------------------------------
        for target in n.links():
            if target == n.base:
                err(n, "links", "a note must not link to itself")
            elif target not in by_base:
                err(n, "links", f"[[{target}]] does not resolve to a note")

    # ---- reciprocity and orphans ------------------------------------------
    inbound: dict[str, set[str]] = {n.base: set() for n in notes}
    for n in notes:
        for t in n.links():
            if t in inbound and t != n.base:
                inbound[t].add(n.base)
    for n in notes:
        for t in n.related_links():
            if t in by_base and n.base not in by_base[t].related_links():
                warn(n, "links", f"[[{t}]] is a one-sided edge - add the matching line there")
        if not n.links() and not inbound[n.base] and len(notes) > 1:
            warn(n, "links", "orphan - no note links to it and it links to nothing")

    return sorted(issues, key=lambda i: (i.rel, i.field))


def ticket_docs_issues(root: str, notes: list[Note], arts: list[agile.Artifact]) -> list[agile.Issue]:
    """The tracker half of the contract, reported alongside the knowledge-base half.

    agile.py owns the authoritative check (it is what /agile:work and
    /agile:close run); this mirrors it so `kb.py lint` alone is enough to see
    a broken ticket->note edge.
    """
    issues: list[agile.Issue] = []
    for a in arts:
        if a.kind not in ("task", "bug"):
            continue
        for entry in a.listfield("docs"):
            if not resolve(notes, str(entry)):
                issues.append(agile.Issue(a.rel, "docs",
                                          f"'{entry}' does not resolve to a knowledge-base note"))
    return issues


