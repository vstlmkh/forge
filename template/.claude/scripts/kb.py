#!/usr/bin/env python3
"""kb.py - consistency engine for the project knowledge base.

Stdlib only. Reuses agile.py's restricted frontmatter parser, so the knowledge
base and the tracker speak the same dialect. Reads every note under
<kb>/<scope>/<type>/, validates it against <kb>/README.md, and regenerates
<kb>/INDEX.md deterministically. The scopes come from `forge.json`; the eight
types are part of the convention and are the same in every project.

Commands
    index                       regenerate <kb>/INDEX.md
    lint                        validate only, print PATH:FIELD: LEVEL: MESSAGE
    new <type> <scope> <description...>
                                create a skeleton note, print its path
                                  [--ticket TASK-0001] [--title "..."]
    find <keyword> [...]        notes matching every keyword (title, labels, body)
    for-ticket <ID>             notes bound to a ticket, plus that ticket's docs:
    show <basename|path>        print JSON {path, frontmatter, sections}
                                  (quote it - basenames contain spaces and braces)
    related <basename>          outbound links, inbound links, one-sided edges
    types                       print the legal type/scope vocabulary

Exit codes
    0  clean
    1  fatal (unreadable file, missing directory, bad arguments)
    2  integrity issues found (index still written)
"""

from __future__ import annotations

import json
import os
import re
import sys

sys.dont_write_bytecode = True   # never leave __pycache__ in the repo
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import agile     # noqa: E402  - same directory, shares the frontmatter grammar
import forge as forgecfg  # noqa: E402

# --------------------------------------------------------------------------
# vocabulary - the types are universal, the scopes come from forge.json
# --------------------------------------------------------------------------

TYPES: dict[str, list[str]] = forgecfg.KB_TYPES

NOTE_STATUSES = ["current", "superseded"]

REQUIRED_FIELDS = [
    "type", "scope", "title", "status", "created", "updated",
    "tickets", "superseded_by", "labels",
]

MAX_BASENAME = 80

BANNER = (
    "<!-- GENERATED by .claude/scripts/kb.py - DO NOT EDIT. "
    "Run: python3 .claude/scripts/kb.py index -->"
)

DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
# the description: lowercase words, separated by single spaces; a hyphen is
# allowed inside a word so `docker-compose` survives
DESC_RE = re.compile(r"^[a-z0-9]+(?:[ -][a-z0-9]+)*$")
WIKILINK_RE = re.compile(r"\[\[([^\]|#]+?)(?:\|[^\]]*)?\]\]")
# {type} description - yyyy-mm-dd   - the braces are literal; see <kb>/README.md.
# desc is greedy so the separator binds to the last " - ", and DESC_RE then
# rejects anything that leaves a stray hyphen behind.
NAME_RE = re.compile(
    r"^\{(?P<type>[a-z-]+)\} (?P<desc>[a-z0-9][a-z0-9 -]*) - (?P<date>\d{4}-\d{2}-\d{2})$"
)


def kb_scopes(root: str) -> list[str]:
    return forgecfg.load(root).kb_scopes


def scope_locked(root: str) -> dict[str, set[str]]:
    return forgecfg.load(root).kb_locked_types


