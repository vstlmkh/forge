def render_index(root: str, notes: list[Note], issues: list[agile.Issue]) -> str:
    cfg = forgecfg.load(root)
    SCOPES = cfg.kb_scopes
    LOCKED = cfg.kb_locked_types
    current = [n for n in notes if n.status != "superseded"]
    gone = [n for n in notes if n.status == "superseded"]

    out = [BANNER, "", "# Knowledge index", "",
           f"What we know about {cfg.project_name}, by scope and type. The convention is in",
           "[`README.md`](README.md); the graph lives in each note's `## Related`",
           "section, not here.", ""]

    out.append(f"{len(notes)} note(s): {len(current)} current, {len(gone)} superseded.")
    out.append("")

    # coverage matrix - zeros are the point, they are the backlog
    out.append("## Coverage")
    out.append("")
    out.append("| Type | " + " | ".join(SCOPES) + " |")
    out.append("|---|" + "---|" * len(SCOPES))
    for t in sorted(TYPES):
        cells = []
        for s in SCOPES:
            if t in LOCKED and s not in LOCKED[t]:
                cells.append("&mdash;")
                continue
            k = sum(1 for n in current if n.fm.get("type") == t and n.fm.get("scope") == s)
            cells.append(str(k) if k else "_0_")
        out.append(f"| `{t}` | " + " | ".join(cells) + " |")
    out.append("")

    for s in SCOPES:
        here = [n for n in current if n.fm.get("scope") == s]
        out.append(f"## {s}")
        out.append("")
        if not here:
            out.append("_No notes yet._")
            out.append("")
            continue
        for t in sorted(TYPES):
            group = sorted((n for n in here if n.fm.get("type") == t), key=lambda n: n.base)
            if not group:
                continue
            out.append(f"### {t}")
            out.append("")
            for n in group:
                tickets = ", ".join(f"`{x}`" for x in n.listfield("tickets")) or "&ndash;"
                labels = ", ".join(f"`{x}`" for x in n.listfield("labels"))
                bits = [f"updated {n.fm.get('updated')}", tickets]
                if labels:
                    bits.append(labels)
                link = n.wrel.replace(os.sep, "/")
                out.append(f"- [{n.title}]({link}) &middot; `[[{n.base}]]` &middot; "
                           + " &middot; ".join(bits))
            out.append("")

    if gone:
        out.append("## Superseded")
        out.append("")
        for n in sorted(gone, key=lambda n: n.base):
            link = n.wrel.replace(os.sep, "/")
            out.append(f"- [{n.title}]({link}) &rarr; `[[{n.fm.get('superseded_by')}]]`")
        out.append("")

    if issues:
        errs = [i for i in issues if i.level == "ERROR"]
        out.append("## Integrity")
        out.append("")
        out.append(f"`kb.py lint` reports {len(errs)} error(s) and "
                   f"{len(issues) - len(errs)} warning(s):")
        out.append("")
        for i in issues:
            out.append(f"- `{i.rel}` **{i.field}** - {i.level}: {i.msg}")
        out.append("")

    return "\n".join(out).rstrip() + "\n"


