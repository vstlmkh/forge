def cmd_index(root: str, notes: list[Note], arts) -> int:
    issues = validate(root, notes, arts) + ticket_docs_issues(root, notes, arts)
    path = os.path.join(kb_dir(root), "INDEX.md")
    content = render_index(root, notes, issues)
    old = None
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            old = fh.read()
    if old != content:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
    errs = sum(1 for i in issues if i.level == "ERROR")
    print(f"kb index: {len(notes)} note(s), {errs} error(s), "
          f"{len(issues) - errs} warning(s)"
          f"{'' if old == content else ' - INDEX.md updated'}")
    return 2 if issues else 0


def cmd_lint(root: str, notes: list[Note], arts) -> int:
    issues = validate(root, notes, arts) + ticket_docs_issues(root, notes, arts)
    for i in issues:
        print(i)
    if not issues:
        print(f"kb lint: clean ({len(notes)} note(s))")
    return 2 if issues else 0


