class Note(agile.Artifact):
    """A knowledge-base note. Inherits has_section / listfield from agile.Artifact."""

    def __init__(self, path, rel, wrel, fm, body):
        super().__init__(path, rel, fm, body)
        self.wrel = wrel                                  # relative to the kb root
        self.base = os.path.basename(rel)[:-3]            # basename, no .md
        parts = wrel.split(os.sep)
        self.dir_scope = parts[0] if len(parts) > 2 else None
        self.dir_type = parts[1] if len(parts) > 2 else None

    @property
    def title(self) -> str:
        return self.fm.get("title") or ""

    def links(self) -> list[str]:
        """Outbound wikilink targets, in document order, deduplicated."""
        seen, out = set(), []
        for m in WIKILINK_RE.finditer(self.body):
            target = m.group(1).strip()
            if target.endswith(".md"):
                target = target[:-3]
            target = os.path.basename(target)
            if target and target not in seen:
                seen.add(target)
                out.append(target)
        return out

    def related_links(self) -> list[str]:
        """Outbound links that appear under the `## Related` heading."""
        m = re.search(r"^##\s+Related\s*$", self.body, re.MULTILINE)
        if not m:
            return []
        rest = self.body[m.end():]
        nxt = re.search(r"^##\s+", rest, re.MULTILINE)
        chunk = rest[: nxt.start()] if nxt else rest
        return [os.path.basename(t.strip()[:-3] if t.strip().endswith(".md") else t.strip())
                for t in WIKILINK_RE.findall(chunk)]


def kb_dir(root: str) -> str:
    return forgecfg.load(root).kb_dir()


def load_notes(root: str) -> tuple[list[Note], list[str]]:
    kb = kb_dir(root)
    rel_kb = forgecfg.load(root).kb_rel
    if not os.path.isdir(kb):
        raise SystemExit(
            f"fatal: {kb} does not exist - create it per {rel_kb}/README.md "
            "(<scope>/<type>/ folders materialise on the first `kb.py new`)"
        )
    notes: list[Note] = []
    fatal: list[str] = []
    for dirpath, dirnames, filenames in os.walk(kb):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        for name in sorted(filenames):
            if not name.endswith(".md") or name.startswith("."):
                continue
            if name in ("README.md", "INDEX.md") and os.path.samefile(dirpath, kb):
                continue
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, root)
            wrel = os.path.relpath(path, kb)
            try:
                with open(path, encoding="utf-8") as fh:
                    text = fh.read()
                fm = agile.parse_frontmatter(text)
            except (OSError, agile.ParseError) as exc:
                fatal.append(f"{rel}: {exc}")
                continue
            body = text.split("\n---", 1)[-1]
            notes.append(Note(path, rel, wrel, fm, body))
    return notes, fatal


def resolve(notes: list[Note], ident: str) -> Note | None:
    """Resolve a basename, a kb-relative path or a repo-relative path."""
    ident = ident.strip()
    if ident.endswith(".md"):
        ident = ident[:-3]
    cands = [n for n in notes if n.base == os.path.basename(ident)]
    if len(cands) == 1:
        return cands[0]
    for n in notes:
        if ident in (n.wrel[:-3], n.rel[:-3]):
            return n
    return cands[0] if cands else None


