def cmd_new(root: str, notes: list[Note], arts, argv: list[str]) -> int:
    cfg = forgecfg.load(root)
    SCOPES = cfg.kb_scopes
    LOCKED = cfg.kb_locked_types
    ticket, title = None, None
    args = []
    i = 0
    while i < len(argv):
        if argv[i] == "--ticket" and i + 1 < len(argv):
            ticket = argv[i + 1]; i += 2; continue
        if argv[i] == "--title" and i + 1 < len(argv):
            title = argv[i + 1]; i += 2; continue
        args.append(argv[i]); i += 1
    if len(args) < 3:
        print('fatal: new <type> <scope> <description...> [--ticket ID] [--title "..."]',
              file=sys.stderr)
        return 1
    # the description may arrive quoted as one argument or as several words
    ntype, scope, desc = args[0], args[1], " ".join(args[2:])
    if ntype not in TYPES:
        print(f"fatal: unknown type '{ntype}', expected one of {sorted(TYPES)}", file=sys.stderr)
        return 1
    # a tracker scope is accepted and mapped to its knowledge-base scope
    if scope not in SCOPES and scope in cfg.scopes:
        scope = cfg.kb_scope_of(scope)
    if scope not in SCOPES:
        print(f"fatal: unknown scope '{scope}', expected one of {SCOPES}", file=sys.stderr)
        return 1
    if ntype in LOCKED and scope not in LOCKED[ntype]:
        print(f"fatal: type '{ntype}' may only live in {sorted(LOCKED[ntype])}", file=sys.stderr)
        return 1
    desc = re.sub(r"\s+", " ", desc.replace("_", " ").lower()).strip(" -")
    desc = re.sub(r" +", " ", re.sub(r"[^a-z0-9 -]", "", desc))
    if not DESC_RE.match(desc):
        print("fatal: the description must reduce to lowercase words separated by spaces",
              file=sys.stderr)
        return 1

    today = agile.datetime.now(agile.timezone.utc).strftime("%Y-%m-%d")
    base = f"{{{ntype}}} {desc} - {today}"
    if len(base) + 3 > MAX_BASENAME:
        print(f"fatal: '{base}.md' is {len(base) + 3} chars, the limit is {MAX_BASENAME} - "
              "shorten the description", file=sys.stderr)
        return 1
    if resolve(notes, base):
        print(f"fatal: {base}.md already exists - update it instead of creating a near-duplicate",
              file=sys.stderr)
        return 1
    if ticket and ticket not in {a.id for a in arts if a.id}:
        print(f"fatal: '{ticket}' does not resolve to an artifact in the tracker", file=sys.stderr)
        return 1

    d = os.path.join(kb_dir(root), scope, ntype)
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, base + ".md")

    fm = [
        "---",
        f"type: {ntype}",
        f"scope: {scope}",
        f"title: {title or desc.capitalize()}",
        "status: current",
        f"created: {today}",
        f"updated: {today}",
        f"tickets: [{ticket}]" if ticket else "tickets: []",
        "superseded_by: null",
        "labels: []",
        "---",
        "",
        f"# {title or desc.capitalize()}",
        "",
    ]
    body = []
    for heading, hint in SKELETON[ntype].items():
        body += [f"## {heading}", "", f"_{hint}_", ""]
    body += ["## Related", "", "- _none yet_", ""]

    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(fm + body))
    print(os.path.relpath(path, root))
    if not title:
        print("note: `title:` is a placeholder - replace it with the finding as a sentence",
              file=sys.stderr)
    return 0


def cmd_find(root: str, notes: list[Note], argv: list[str]) -> int:
    if not argv:
        print("fatal: find needs at least one keyword", file=sys.stderr)
        return 1
    words = [w.lower() for w in argv]
    hits = []
    for n in notes:
        hay = "\n".join([n.base, n.title, " ".join(str(x) for x in n.listfield("labels")),
                         " ".join(str(x) for x in n.listfield("tickets")), n.body]).lower()
        if all(w in hay for w in words):
            where = "title" if all(w in (n.base + " " + n.title).lower() for w in words) else "body"
            hits.append((n, where))
    for n, where in sorted(hits, key=lambda h: (h[1] != "title", h[0].wrel)):
        print(f"{os.path.relpath(n.path, root)}\t{n.fm.get('type')}\t{n.title}\t[{where}]")
    if not hits:
        print(f"no note matches {words} - this is a gap, not an answer", file=sys.stderr)
        return 2
    return 0


def cmd_for_ticket(root: str, notes: list[Note], arts, ident: str) -> int:
    art = next((a for a in arts if a.id == ident), None)
    if art is None:
        print(f"fatal: no artifact with id '{ident}'", file=sys.stderr)
        return 1
    declared = [str(x) for x in art.listfield("docs")]
    backrefs = [n for n in notes if ident in [str(x) for x in n.listfield("tickets")]]
    print(f"{ident} ({art.kind}, scope {art.fm.get('scope')}, status {art.status})")
    print("docs: on the ticket:")
    for entry in declared or []:
        n = resolve(notes, entry)
        print(f"  {'OK ' if n else 'MISSING '} {entry}" + (f"\t{n.title}" if n else ""))
    if not declared:
        waiver = art.fm.get("docs_waiver")
        print(f"  (none){' - waiver: ' + str(waiver) if waiver else ' - and no waiver'}")
    print("notes claiming this ticket:")
    for n in sorted(backrefs, key=lambda n: n.wrel):
        print(f"  {os.path.relpath(n.path, root)}\t{n.title}")
    if not backrefs:
        print("  (none)")
    # A ticket may legitimately *read* a note without touching it - `tickets:`
    # records what produced or last confirmed the note, not who consulted it.
    # So an asymmetry is information, not a defect.
    read_only = [e for e in declared
                 if resolve(notes, e) and ident not in
                 [str(x) for x in resolve(notes, e).listfield("tickets")]]
    if read_only:
        print("read but not claimed (consulted, never updated by this ticket):")
        for e in read_only:
            print(f"  {e}")
    return 2 if [e for e in declared if not resolve(notes, e)] else 0


def cmd_show(root: str, notes: list[Note], ident: str) -> int:
    n = resolve(notes, ident)
    if n is None:
        print(f"fatal: no note matching '{ident}'", file=sys.stderr)
        return 1
    sections = [m.group(1).strip() for m in re.finditer(r"^##\s+(.+?)\s*$", n.body, re.MULTILINE)]
    print(json.dumps({"path": n.rel, "basename": n.base, "frontmatter": n.fm,
                      "sections": sections, "links": n.links()}, indent=2, sort_keys=True))
    return 0


def cmd_related(root: str, notes: list[Note], ident: str) -> int:
    n = resolve(notes, ident)
    if n is None:
        print(f"fatal: no note matching '{ident}'", file=sys.stderr)
        return 1
    by_base = {x.base: x for x in notes}
    print(f"{n.base}\t{n.title}")
    print("out:")
    for t in n.links():
        tgt = by_base.get(t)
        print(f"  {'->' if tgt else '?? '} {t}" + (f"\t{tgt.title}" if tgt else "\tUNRESOLVED"))
    if not n.links():
        print("  (none)")
    print("in:")
    inbound = [x for x in notes if n.base in x.links()]
    for x in sorted(inbound, key=lambda x: x.base):
        print(f"  <- {x.base}\t{x.title}")
    if not inbound:
        print("  (none)")
    one_sided = [t for t in n.related_links()
                 if t in by_base and n.base not in by_base[t].related_links()]
    for t in one_sided:
        print(f"warn: [[{t}]] does not link back - add the matching '## Related' line there",
              file=sys.stderr)
    return 2 if one_sided else 0


def cmd_types(root: str) -> int:
    cfg = forgecfg.load(root)
    print(f"scopes: {', '.join(cfg.kb_scopes)}")
    for t in sorted(TYPES):
        locked = cfg.kb_locked_types.get(t)
        lock = f"  [{'/'.join(sorted(locked))} only]" if locked else ""
        print(f"{t}{lock}\n  sections: " + " | ".join(TYPES[t] + ["Related"]))
    return 0


USAGE = __doc__


def main(argv: list[str]) -> int:
    args = list(argv[1:])
    root_arg = None
    if "--root" in args:
        i = args.index("--root")
        try:
            root_arg = args[i + 1]
        except IndexError:
            print("fatal: --root needs a path", file=sys.stderr)
            return 1
        del args[i:i + 2]
    if not args or args[0] in ("-h", "--help", "help"):
        print(USAGE)
        return 0 if args else 1

    root = agile.find_root(root_arg)
    cmd = args[0]
    if cmd == "types":
        return cmd_types(root)

    notes, fatal = load_notes(root)
    arts, afatal = agile.load_all(root)
    if fatal or afatal:
        for f in fatal + afatal:
            print(f"fatal: {f}", file=sys.stderr)
        return 1

    if cmd == "index":
        return cmd_index(root, notes, arts)
    if cmd == "lint":
        return cmd_lint(root, notes, arts)
    if cmd == "new":
        return cmd_new(root, notes, arts, args[1:])
    if cmd == "find":
        return cmd_find(root, notes, args[1:])
    if cmd == "for-ticket":
        if len(args) < 2:
            print("fatal: for-ticket needs a ticket ID", file=sys.stderr)
            return 1
        return cmd_for_ticket(root, notes, arts, args[1])
    if cmd == "show":
        if len(args) < 2:
            print("fatal: show needs a basename or path", file=sys.stderr)
            return 1
        return cmd_show(root, notes, args[1])
    if cmd == "related":
        if len(args) < 2:
            print("fatal: related needs a basename or path", file=sys.stderr)
            return 1
        return cmd_related(root, notes, args[1])
    print(f"fatal: unknown command '{cmd}'", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
