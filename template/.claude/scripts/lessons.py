class Lesson(agile.Artifact):
    """One rule. Inherits has_section / listfield / section from agile.Artifact."""

    def __init__(self, path, rel, wrel, fm, body):
        super().__init__(path, rel, fm, body)
        self.wrel = wrel                                  # relative to the lessons root
        self.base = os.path.basename(rel)[:-3]            # basename, no .md
        parts = wrel.split(os.sep)
        self.dir_scope = parts[0] if len(parts) > 1 else None

    @property
    def rule(self) -> str:
        return str(self.fm.get("rule") or "")

    @property
    def lscope(self) -> str:
        return str(self.fm.get("scope") or "")

    @property
    def roles(self) -> list[str]:
        return [str(r) for r in self.listfield("roles")]

    @property
    def confirmations(self) -> int:
        try:
            return int(self.fm.get("confirmations") or 0)
        except (TypeError, ValueError):
            return -1

    def addresses(self, scope: str | None, role: str | None) -> bool:
        """Does this lesson speak to that audience? A missing axis matches
        everything, which is what makes `for <scope>` and `for <role>` useful
        on their own."""
        if scope is not None and self.lscope not in (scope, ALL):
            return False
        if role is not None and role not in self.roles and ALL not in self.roles:
            return False
        return True

    def weight(self) -> tuple:
        """Ranking key for the budgeted hand-off: a rule that has caught the
        same mistake four times outranks one filed yesterday, and a rule nobody
        has confirmed in a year sinks below both."""
        return (-self.confirmations, str(self.fm.get("last_confirmed") or ""), self.id)

    def links(self) -> list[str]:
        seen, out = set(), []
        for m in WIKILINK_RE.finditer(self.body):
            target = m.group(1).strip()
            if target.endswith(".md"):
                target = target[:-3]
            target = os.path.basename(target)
            if target and target not in seen:
                seen.add(target)
                out.append(target)
        return out


def lessons_dir(root: str) -> str:
    return forgecfg.load(root).lessons_dir()


def load_lessons(root: str) -> tuple[list[Lesson], list[str]]:
    cfg = forgecfg.load(root)
    base = cfg.lessons_dir()
    if not os.path.isdir(base):
        raise SystemExit(
            f"fatal: {base} does not exist - run `forge upgrade` to create it, "
            f"then see {cfg.lessons_rel}/README.md"
        )
    out: list[Lesson] = []
    fatal: list[str] = []
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        for name in sorted(filenames):
            if not name.endswith(".md") or name.startswith("."):
                continue
            if name in ("README.md", "INDEX.md") and os.path.samefile(dirpath, base):
                continue
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, root)
            wrel = os.path.relpath(path, base)
            try:
                with open(path, encoding="utf-8") as fh:
                    text = fh.read()
                fm = agile.parse_frontmatter(text)
            except (OSError, agile.ParseError) as exc:
                fatal.append(f"{rel}: {exc}")
                continue
            out.append(Lesson(path, rel, wrel, fm, text.split("\n---", 1)[-1]))
    return out, fatal


def resolve(lessons: list[Lesson], ident: str) -> Lesson | None:
    ident = str(ident).strip()
    if ident.endswith(".md"):
        ident = ident[:-3]
    for l in lessons:
        if l.id == ident:
            return l
    for l in lessons:
        if l.base == os.path.basename(ident) or ident in (l.wrel[:-3], l.rel[:-3]):
            return l
    return None


