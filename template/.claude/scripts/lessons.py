def render_index(root: str, lessons: list[Lesson], issues: list[agile.Issue]) -> str:
    cfg = forgecfg.load(root)
    active = [l for l in lessons if l.status == "active"]
    gone = [l for l in lessons if l.status != "active"]

    out = [BANNER, "", "# Lessons", "",
           f"What {cfg.project_name} has taught its agents, by scope. One rule per file;",
           "the rule itself is the whole index entry. The convention is in",
           "[`README.md`](README.md).", "",
           f"{len(lessons)} lesson(s): {len(active)} active, {len(gone)} retired or superseded.",
           ""]

    for scope in cfg.lesson_scopes():
        here = sorted((l for l in active if l.lscope == scope), key=lambda l: l.weight())
        if not here:
            continue
        out += [f"## {scope}", "",
                "| | Rule | Roles | Gate | Confirmed |", "|---|---|---|---|---|"]
        for l in here:
            link = l.wrel.replace(os.sep, "/")
            gate = l.fm.get("gate")
            out.append(f"| [`{l.id}`]({link}) | {l.rule} | {', '.join(l.roles)} | "
                       f"{gate if gate is not None else '&ndash;'} | "
                       f"{l.fm.get('last_confirmed')} &times;{l.confirmations} |")
        out.append("")

    if gone:
        out += ["## Retired and superseded", ""]
        for l in sorted(gone, key=lambda l: l.id):
            link = l.wrel.replace(os.sep, "/")
            tail = (f" &rarr; `{l.fm.get('superseded_by')}`"
                    if l.status == "superseded" else "")
            out.append(f"- [`{l.id}`]({link}) _{l.status}_ &middot; {l.rule}{tail}")
        out.append("")

    if issues:
        errs = [i for i in issues if i.level == "ERROR"]
        out += ["## Integrity", "",
                f"`lessons.py lint` reports {len(errs)} error(s) and "
                f"{len(issues) - len(errs)} warning(s):", ""]
        for i in issues:
            out.append(f"- `{i.rel}` **{i.field}** - {i.level}: {i.msg}")
        out.append("")

    credit = cfg.credit()
    if credit:
        out += ["---", "", credit, ""]
    return "\n".join(out).rstrip() + "\n"


