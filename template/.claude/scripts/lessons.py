#!/usr/bin/env python3
"""lessons.py - what this project taught its agents, in a form they can afford to read.

`docs/agile/` records what we are doing and `docs/knowledge/` what we know about
the product. This records **how work goes wrong here**: the rule a ticket paid
for by bouncing off a gate. One rule per file, one line per rule.

The one-line `rule:` is the whole design. It is what an agent is handed at the
start of a gate; the body is read only when the line turns out to matter. A
layer that cannot be read cheaply is a layer that does not get read, so the
budget in `for` is a hard cap, not a suggestion, and `lint` refuses a rule that
does not fit on a line.

Stdlib only. Shares agile.py's frontmatter grammar, so a lesson, a ticket and a
knowledge-base note are all parsed by the same restricted reader.

Commands
    for <agent|role|scope>      the rules that agent must obey, ranked and capped
                                  [--scope S] [--budget N] [--paths]
    list [--scope S] [--role R] [--retired]
                                one line per lesson
    show <LESSON-NNNN>          the whole file, path first
    new "<description>" --scope S --roles r,r [--rule "..."]
                                  [--ticket ID] [--gate N]
    confirm <LESSON-NNNN> [--ticket ID]
                                this lesson just proved itself again
    retire <LESSON-NNNN> --reason "..."
    supersede <LESSON-NNNN> --by <LESSON-NNNN>
    audit                       the decision queue: every active rule with its age,
                                  its weight and who the budget hides it from
    lint                        validate only, print PATH:FIELD: LEVEL: MESSAGE
    index                       regenerate <lessons>/INDEX.md
    roles                       print the legal scope/role vocabulary

Exit codes
    0  clean
    1  fatal (unreadable file, bad arguments)
    2  integrity issues found (index still written)
"""

from __future__ import annotations

import datetime
import os
import re
import sys

sys.dont_write_bytecode = True   # never leave __pycache__ in the repo
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import agile     # noqa: E402  - same directory, shares the frontmatter grammar
import forge as forgecfg  # noqa: E402

ROLES = forgecfg.LESSON_ROLES
ALL = forgecfg.LESSON_ALL

STATUSES = ["active", "retired", "superseded"]

REQUIRED_FIELDS = [
    "id", "scope", "roles", "rule", "status", "gate",
    "tickets", "confirmations", "last_confirmed",
    "created", "updated", "superseded_by",
]

# A lesson is addressed by its id, not by its basename: a ticket carries
# `lessons: [LESSON-0003]` and an agent is handed the same token back. That is
# why the filename leads with the id and drops the knowledge base's braced type
# and trailing date - there is only one type here, and the date is in the
# frontmatter where nothing has to re-read a path to get at it.
ID_RE = re.compile(r"^LESSON-\d{4}$")
NAME_RE = re.compile(r"^(?P<id>LESSON-\d{4}) (?P<desc>[a-z0-9][a-z0-9 -]*)$")
DESC_RE = re.compile(r"^[a-z0-9]+(?:[ -][a-z0-9]+)*$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
WIKILINK_RE = re.compile(r"\[\[([^\]|#]+?)(?:\|[^\]]*)?\]\]")

MAX_BASENAME = 72
# The rule has to survive being quoted inside somebody else's prompt. One line.
MAX_RULE = 120
MIN_RULE = 20
# Not a style rule: every line here is paid for out of the agent's context on
# the turn it reads the file. A lesson that needs an essay is a knowledge-base
# note wearing a lesson's hat.
MAX_BODY_LINES = 40

SECTIONS = ["Why", "How to apply", "Evidence"]

BANNER = (
    "<!-- GENERATED by .claude/scripts/lessons.py - DO NOT EDIT. "
    "Run: python3 .claude/scripts/lessons.py index -->"
)


def today() -> str:
    return datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")


def days_since(iso: str) -> int | None:
    if not DATE_RE.match(str(iso)):
        return None
    try:
        then = datetime.date.fromisoformat(str(iso))
    except ValueError:
        return None
    return (datetime.date.today() - then).days


