def validate(root: str, lessons: list[Lesson], arts: list[agile.Artifact]) -> list[agile.Issue]:
    cfg = forgecfg.load(root)
    issues: list[agile.Issue] = []
    scopes = cfg.lesson_scopes()
    ticket_ids = {a.id for a in arts if a.id}
    ngates = len(agile.GATES)

    def err(l, field, msg):
        issues.append(agile.Issue(l.rel, field, msg))

    def warn(l, field, msg):
        issues.append(agile.Issue(l.rel, field, msg, "WARN"))

    by_id: dict[str, Lesson] = {}
    for l in lessons:
        if not ID_RE.match(l.id):
            err(l, "id", f"'{l.id}' is not LESSON-NNNN")
        elif l.id in by_id:
            err(l, "id", f"duplicate id, also used by {by_id[l.id].rel}")
        else:
            by_id[l.id] = l

    for l in lessons:
        # ---- location and filename ----------------------------------------
        if l.dir_scope is None:
            err(l, "path", f"a lesson lives at {cfg.lessons_rel}/<scope>/<file>.md, never higher")
            continue
        if l.dir_scope not in scopes:
            err(l, "path", f"'{l.dir_scope}' is not one of {scopes}")
        m = NAME_RE.match(l.base)
        if not m:
            err(l, "filename", "must be 'LESSON-NNNN <description>.md' - lowercase "
                               "words after the id, no date (it is in the frontmatter)")
        else:
            if m.group("id") != l.id:
                err(l, "filename", f"'{m.group('id')}' contradicts id: {l.id}")
            if not DESC_RE.match(m.group("desc")):
                err(l, "filename",
                    f"description '{m.group('desc')}' must be lowercase words separated by spaces")
        if len(os.path.basename(l.rel)) > MAX_BASENAME:
            err(l, "filename", f"{len(os.path.basename(l.rel))} chars, the limit is {MAX_BASENAME}")

        # ---- frontmatter --------------------------------------------------
        for f in REQUIRED_FIELDS:
            if f not in l.fm:
                err(l, f, "field is missing")

        if l.lscope not in scopes:
            err(l, "scope", f"'{l.lscope}' is not one of {scopes}")
        elif l.dir_scope in scopes and l.lscope != l.dir_scope:
            err(l, "scope", f"'{l.lscope}' contradicts the folder '{l.dir_scope}'")

        roles = l.roles
        if not roles:
            err(l, "roles", f"name the identities that must obey this: {list(ROLES)} or [{ALL}]")
        for r in roles:
            if r not in ROLES and r != ALL:
                err(l, "roles", f"'{r}' is not one of {list(ROLES)} or '{ALL}'")
        if ALL in roles and len(roles) > 1:
            err(l, "roles", f"'{ALL}' already means every role - drop the rest")

        rule = l.rule
        if not rule:
            err(l, "rule", "must state the rule as one imperative line - it is what an "
                           "agent is handed, and an empty one costs context for nothing")
        else:
            if "\n" in rule:
                err(l, "rule", "must be a single line")
            if len(rule) > MAX_RULE:
                err(l, "rule", f"{len(rule)} chars, the limit is {MAX_RULE} - "
                               "the detail belongs in '## How to apply'")
            elif len(rule) < MIN_RULE:
                warn(l, "rule", "too short to be actionable - state what to do, not a topic")

        if l.status not in STATUSES:
            err(l, "status", f"'{l.status}' is not one of {STATUSES}")

        gate = l.fm.get("gate")
        if gate is not None:
            try:
                g = int(gate)
            except (TypeError, ValueError):
                g = -1
            if not 1 <= g <= ngates:
                err(l, "gate", f"'{gate}' is not a gate number (1-{ngates}) or null")

        if l.confirmations < 0:
            err(l, "confirmations", "must be a non-negative integer")

        for f in ("created", "updated", "last_confirmed"):
            v = l.fm.get(f)
            if v is None:
                err(l, f, "must be a date")
            elif not DATE_RE.match(str(v)):
                err(l, f, f"'{v}' is not YYYY-MM-DD")
        cre = str(l.fm.get("created"))
        for f in ("updated", "last_confirmed"):
            v = str(l.fm.get(f))
            if DATE_RE.match(cre) and DATE_RE.match(v) and v < cre:
                err(l, f, f"'{v}' precedes created '{cre}'")

        # ---- provenance ---------------------------------------------------
        tickets = l.listfield("tickets")
        if not tickets:
            warn(l, "tickets", "no ticket recorded - which failure paid for this rule?")
        for t in tickets:
            if str(t) not in ticket_ids:
                err(l, "tickets", f"'{t}' does not resolve to an artifact in the tracker")

        sb = l.fm.get("superseded_by")
        if l.status == "superseded":
            if not sb:
                err(l, "superseded_by", "a superseded lesson must point at its replacement")
            elif not resolve(lessons, str(sb)):
                err(l, "superseded_by", f"'{sb}' does not resolve to a lesson")
        elif sb:
            err(l, "superseded_by", "set only when status is 'superseded'")

        # ---- body ---------------------------------------------------------
        for heading in SECTIONS:
            if not re.search(r"^##\s+" + re.escape(heading) + r"\s*$", l.body, re.MULTILINE):
                err(l, "body", f"missing section '## {heading}'")
            elif not l.has_section(heading):
                err(l, "body", f"section '## {heading}' is empty or a placeholder")
        if not re.search(r"^##\s+Related\s*$", l.body, re.MULTILINE):
            err(l, "body", "missing section '## Related' - keep it with '- _none yet_' if empty")
        nlines = len([x for x in l.body.splitlines() if x.strip()])
        if nlines > MAX_BODY_LINES:
            warn(l, "body", f"{nlines} non-empty lines, the budget is {MAX_BODY_LINES} - "
                            "an agent pays for every one of them; move the background "
                            f"into {cfg.kb_rel}/ and link it")

        # A link to a lesson must resolve; a link to anything else is a
        # knowledge-base note and is not this script's tree to police.
        for target in l.links():
            if target == l.id or target == l.base:
                err(l, "links", "a lesson must not link to itself")
            elif ID_RE.match(target) and target not in by_id:
                err(l, "links", f"[[{target}]] does not resolve to a lesson")

        # ---- decay ---------------------------------------------------------
        if l.status == "active":
            age = days_since(l.fm.get("last_confirmed"))
            if age is not None and age > cfg.lesson_stale_days:
                warn(l, "last_confirmed",
                     f"{age} days since this was last confirmed (budget "
                     f"{cfg.lesson_stale_days}) - confirm it or retire it; a rule "
                     "nobody has needed in that long is spending context for nothing")

    # ---- duplication ------------------------------------------------------
    seen: dict[str, Lesson] = {}
    for l in sorted((x for x in lessons if x.status == "active"), key=lambda x: x.id):
        key = re.sub(r"[^a-z0-9 ]", "", l.rule.lower()).strip()
        if not key:
            continue
        if key in seen:
            warn(l, "rule", f"reads the same as {seen[key].id} - supersede one of them")
        else:
            seen[key] = l

    return sorted(issues, key=lambda i: (i.rel, i.field))


def ticket_lesson_issues(root: str, lessons: list[Lesson],
                         arts: list[agile.Artifact]) -> list[agile.Issue]:
    """The tracker half of the contract. agile.py owns the authoritative check;
    this mirrors it so `lessons.py lint` alone shows a broken ticket->lesson edge."""
    issues: list[agile.Issue] = []
    for a in arts:
        if a.kind not in ("task", "bug"):
            continue
        for entry in a.listfield("lessons"):
            if not resolve(lessons, str(entry)):
                issues.append(agile.Issue(a.rel, "lessons",
                                          f"'{entry}' does not resolve to a lesson"))
    return issues


