def _flag(argv: list[str], name: str, default=None):
    if name in argv:
        i = argv.index(name)
        if i + 1 < len(argv):
            return argv[i + 1]
    return default


def _strip_flags(argv: list[str], names: tuple[str, ...]) -> list[str]:
    out, i = [], 0
    while i < len(argv):
        if argv[i] in names:
            i += 2
            continue
        if argv[i].startswith("--"):
            i += 1
            continue
        out.append(argv[i])
        i += 1
    return out


def rules_for(root: str, who: str | None, scope: str | None = None,
              budget: int | None = None) -> tuple[list[Lesson], list[Lesson], str]:
    """The rules binding one audience: (shown, withheld, how to name them).

    Factored out of `cmd_for` so that `agile.py handoff` can render the same
    ranked, capped list straight into a dispatch payload. One ranking, one cap,
    one place - a second implementation would drift, and the budget is the
    whole reason this layer is affordable.

    Raises ValueError when `who` names nothing the project has.
    """
    cfg = forgecfg.load(root)
    role = None
    if who:
        if who in cfg.agents or who in forgecfg.AGENT_ALIASES:
            role = cfg.role_of_agent(who)
            scope = scope or cfg.scope_of_agent(who)
        elif who in ROLES:
            role = who
        elif who in cfg.scopes:
            scope = scope or who
        elif who != ALL:
            raise ValueError(
                f"'{who}' is not an agent, a role {list(ROLES)} or a scope "
                f"{list(cfg.scopes)}")
    if budget is None:
        budget = cfg.lesson_budget
    budget = max(1, budget)

    lessons, _fatal = load_lessons(root)
    pool = [l for l in lessons if l.status == "active" and l.addresses(scope, role)]
    pool.sort(key=lambda l: l.weight())
    audience = " / ".join(x for x in (scope, role) if x) or "every agent"
    return pool[:budget], pool[budget:], audience


def cmd_for(root: str, lessons: list[Lesson], argv: list[str]) -> int:
    """The hot path: what one agent must obey, ranked and capped.

    Never fails. It runs at the top of a gate, and an agent that reads a
    non-zero exit here learns to stop running it."""
    cfg = forgecfg.load(root)
    rest = _strip_flags(argv, ("--scope", "--budget"))
    who = rest[0] if rest else None
    try:
        budget = max(1, int(_flag(argv, "--budget", cfg.lesson_budget)))
    except (TypeError, ValueError):
        budget = cfg.lesson_budget
    try:
        shown, withheld, audience = rules_for(root, who, _flag(argv, "--scope"), budget)
    except ValueError as exc:
        print(f"fatal: {exc}", file=sys.stderr)
        return 1
    pool = shown + withheld
    if not pool:
        print(f"lessons for {audience}: none recorded yet.")
        return 0
    print(f"{len(shown)} lesson(s) for {audience}"
          f"{f' - {len(withheld)} more withheld, lowest-ranked first' if withheld else ''}. "
          "These are rules this project paid for; obey them unless the ticket says otherwise.")
    want_paths = "--paths" in argv
    for l in shown:
        line = f"  {l.id}  {l.rule}"
        if want_paths:
            line += f"\n      {l.rel}"
        print(line)
    if withheld:
        # Naming all of them would make this line grow without bound, which is
        # the thing the budget exists to prevent. The count is the part that
        # must never be dropped; the ids are a courtesy.
        named = withheld[:5]
        tail = f", and {len(withheld) - len(named)} more" if len(withheld) > len(named) else ""
        print(f"  (withheld: {', '.join(l.id for l in named)}{tail} - "
              f"`lessons.py list` shows all of them)")
    print("Why one of them exists: python3 .claude/scripts/lessons.py show <LESSON-NNNN>")
    return 0


def cmd_list(root: str, lessons: list[Lesson], argv: list[str]) -> int:
    scope = _flag(argv, "--scope")
    role = _flag(argv, "--role")
    pool = [l for l in lessons if l.addresses(scope, role)]
    if "--retired" not in argv:
        pool = [l for l in pool if l.status == "active"]
    for l in sorted(pool, key=lambda l: (l.lscope, l.weight())):
        print(f"{l.id}\t{l.lscope}\t{','.join(l.roles)}\t{l.status}\t"
              f"x{l.confirmations}\t{l.rule}")
    if not pool:
        print("no lesson matches", file=sys.stderr)
        return 2
    return 0


def cmd_show(root: str, lessons: list[Lesson], ident: str) -> int:
    l = resolve(lessons, ident)
    if l is None:
        print(f"fatal: no lesson matching '{ident}'", file=sys.stderr)
        return 1
    print(f"# {l.rel}")
    with open(l.path, encoding="utf-8") as fh:
        sys.stdout.write(fh.read())
    return 0


SKELETON = {
    "Why": "The failure this prevents, named concretely. A rule whose reason is "
           "invisible gets optimised away by the next agent.",
    "How to apply": "What to do differently, as steps or a command. Not advice - an action.",
    "Evidence": "The ticket and the gate it bounced off, one line each.",
}


def next_id(lessons: list[Lesson]) -> str:
    used = [int(l.id.split("-")[1]) for l in lessons if ID_RE.match(l.id)]
    return f"LESSON-{max(used, default=0) + 1:04d}"


def cmd_new(root: str, lessons: list[Lesson], arts, argv: list[str]) -> int:
    cfg = forgecfg.load(root)
    scope = _flag(argv, "--scope")
    roles = _flag(argv, "--roles")
    rule = _flag(argv, "--rule")
    ticket = _flag(argv, "--ticket")
    gate = _flag(argv, "--gate")
    rest = _strip_flags(argv, ("--scope", "--roles", "--rule", "--ticket", "--gate"))
    if not rest or not scope or not roles:
        print('fatal: new "<description>" --scope <scope|all> --roles <role,role|all> '
              '[--rule "..."] [--ticket ID] [--gate N]', file=sys.stderr)
        return 1
    if scope not in cfg.lesson_scopes():
        print(f"fatal: unknown scope '{scope}', expected one of {cfg.lesson_scopes()}",
              file=sys.stderr)
        return 1
    rl = [r.strip() for r in str(roles).split(",") if r.strip()]
    for r in rl:
        if r not in ROLES and r != ALL:
            print(f"fatal: unknown role '{r}', expected {list(ROLES)} or '{ALL}'",
                  file=sys.stderr)
            return 1
    if ticket and ticket not in {a.id for a in arts if a.id}:
        print(f"fatal: '{ticket}' does not resolve to an artifact in the tracker",
              file=sys.stderr)
        return 1
    if gate is not None:
        try:
            if not 1 <= int(gate) <= len(agile.GATES):
                raise ValueError
        except ValueError:
            print(f"fatal: --gate takes 1-{len(agile.GATES)}", file=sys.stderr)
            return 1

    desc = " ".join(rest)
    desc = re.sub(r"\s+", " ", desc.replace("_", " ").lower()).strip(" -")
    desc = re.sub(r" +", " ", re.sub(r"[^a-z0-9 -]", "", desc))
    if not DESC_RE.match(desc):
        print("fatal: the description must reduce to lowercase words separated by spaces",
              file=sys.stderr)
        return 1
    lid = next_id(lessons)
    base = f"{lid} {desc}"
    if len(base) + 3 > MAX_BASENAME:
        print(f"fatal: '{base}.md' is {len(base) + 3} chars, the limit is {MAX_BASENAME} - "
              "shorten the description", file=sys.stderr)
        return 1

    stamp = today()
    d = os.path.join(cfg.lessons_dir(), scope)
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, base + ".md")
    if os.path.exists(path):
        print(f"fatal: {path} already exists", file=sys.stderr)
        return 1

    fm = [
        "---",
        f"id: {lid}",
        f"scope: {scope}",
        f"roles: [{', '.join(rl)}]",
        f"rule: {rule or desc.capitalize() + ' - REPLACE THIS WITH THE RULE'}",
        "status: active",
        f"gate: {int(gate) if gate is not None else 'null'}",
        f"tickets: [{ticket}]" if ticket else "tickets: []",
        "confirmations: 0",
        f"last_confirmed: {stamp}",
        f"created: {stamp}",
        f"updated: {stamp}",
        "superseded_by: null",
        "---",
        "",
    ]
    body = []
    for heading in SECTIONS:
        body += [f"## {heading}", "", f"_{SKELETON[heading]}_", ""]
    body += ["## Related", "", "- _none yet_", ""]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(fm + body))
    print(os.path.relpath(path, root))
    if not rule:
        print("note: `rule:` is a placeholder - replace it with one imperative line. "
              "It is the only part most agents will ever read.", file=sys.stderr)
    return 0


def cmd_confirm(root: str, lessons: list[Lesson], arts, argv: list[str]) -> int:
    rest = _strip_flags(argv, ("--ticket",))
    if not rest:
        print("fatal: confirm <LESSON-NNNN> [--ticket ID]", file=sys.stderr)
        return 1
    l = resolve(lessons, rest[0])
    if l is None:
        print(f"fatal: no lesson matching '{rest[0]}'", file=sys.stderr)
        return 1
    ticket = _flag(argv, "--ticket")
    if ticket and ticket not in {a.id for a in arts if a.id}:
        print(f"fatal: '{ticket}' does not resolve to an artifact in the tracker",
              file=sys.stderr)
        return 1
    stamp = today()
    values = {"confirmations": l.confirmations + 1,
              "last_confirmed": stamp, "updated": stamp}
    if ticket:
        tickets = [str(t) for t in l.listfield("tickets")]
        if ticket not in tickets:
            values["tickets"] = tickets + [ticket]
    set_fields(l.path, values)
    print(f"{l.id} confirmed ({l.confirmations + 1}x, {stamp})")
    return 0


def cmd_retire(root: str, lessons: list[Lesson], argv: list[str]) -> int:
    rest = _strip_flags(argv, ("--reason",))
    reason = _flag(argv, "--reason")
    if not rest or not reason:
        print('fatal: retire <LESSON-NNNN> --reason "..."', file=sys.stderr)
        return 1
    l = resolve(lessons, rest[0])
    if l is None:
        print(f"fatal: no lesson matching '{rest[0]}'", file=sys.stderr)
        return 1
    stamp = today()
    set_fields(l.path, {"status": "retired", "updated": stamp})
    append_to_section(l.path, "Evidence", f"- retired {stamp}: {reason}")
    print(f"{l.id} retired")
    return 0


def cmd_supersede(root: str, lessons: list[Lesson], argv: list[str]) -> int:
    rest = _strip_flags(argv, ("--by",))
    by = _flag(argv, "--by")
    if not rest or not by:
        print("fatal: supersede <LESSON-NNNN> --by <LESSON-NNNN>", file=sys.stderr)
        return 1
    l, repl = resolve(lessons, rest[0]), resolve(lessons, by)
    if l is None or repl is None:
        print(f"fatal: no lesson matching '{rest[0] if l is None else by}'", file=sys.stderr)
        return 1
    if l.id == repl.id:
        print("fatal: a lesson cannot supersede itself", file=sys.stderr)
        return 1
    stamp = today()
    set_fields(l.path, {"status": "superseded", "superseded_by": repl.id, "updated": stamp})
    append_to_section(l.path, "Evidence", f"- superseded {stamp} by [[{repl.id}]]")
    print(f"{l.id} superseded by {repl.id}")
    return 0


def cmd_audit(root: str, lessons: list[Lesson], arts) -> int:
    """What a retrospective has to decide, and nothing it can decide alone.

    Every verdict here is a judgement - whether two rules are really the same
    rule, whether an unconfirmed one is stale or merely lucky - so this prints
    the queue and the evidence, and stops. `confirm`, `retire` and `supersede`
    are one call away and are deliberately not called from here."""
    cfg = forgecfg.load(root)
    live = [l for l in lessons if l.status == "active"]
    by_ticket_status = {a.id: a.status for a in arts if a.id}

    # Who actually receives what. The budget bites per audience, not per scope:
    # a rule filed under `all` can sit inside one agent's dozen and outside
    # another's, and reporting it by folder would hide exactly that.
    hidden_from: dict[str, list[str]] = {l.id: [] for l in live}
    for agent in cfg.agents:
        pool = sorted((l for l in live
                       if l.addresses(cfg.scope_of_agent(agent), cfg.role_of_agent(agent))),
                      key=lambda l: l.weight())
        for l in pool[cfg.lesson_budget:]:
            hidden_from[l.id].append(agent)

    print(f"{len(live)} active rule(s), budget {cfg.lesson_budget} per hand-off, "
          f"stale after {cfg.lesson_stale_days} days.")
    for scope in cfg.lesson_scopes():
        here = sorted((l for l in live if l.lscope == scope), key=lambda l: l.weight())
        if not here:
            continue
        print(f"\n## {scope}")
        for l in here:
            age = days_since(l.fm.get("last_confirmed"))
            flags = []
            if age is not None and age > cfg.lesson_stale_days:
                flags.append(f"STALE {age}d")
            if l.confirmations == 0 and (age or 0) > cfg.lesson_stale_days // 2:
                flags.append("NEVER CONFIRMED")
            if hidden_from[l.id]:
                flags.append("BELOW THE BUDGET, never reaches: " + ", ".join(hidden_from[l.id]))
            still_open = [t for t in (str(x) for x in l.listfield("tickets"))
                          if by_ticket_status.get(t) not in (None, "done", "cancelled",
                                                             "wontfix", "cannot_reproduce")]
            if still_open:
                flags.append("ticket still open: " + ", ".join(still_open))
            print(f"  {l.id}  x{l.confirmations}  {l.fm.get('last_confirmed')}  "
                  f"{'[' + '; '.join(flags) + ']' if flags else ''}")
            print(f"      {l.rule}")

    issues = [i for i in validate(root, lessons, arts)
              if i.level == "WARN" and i.field in ("rule", "last_confirmed")]
    if issues:
        print("\nWhat lint already suspects:")
        for i in issues:
            print(f"  {i.rel}\n    {i.msg}")
    print("\nNothing here is a verdict. Resolve each with confirm, retire or supersede.")
    return 0


def cmd_index(root: str, lessons: list[Lesson], arts) -> int:
    issues = validate(root, lessons, arts) + ticket_lesson_issues(root, lessons, arts)
    path = os.path.join(lessons_dir(root), "INDEX.md")
    content = render_index(root, lessons, issues)
    old = None
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            old = fh.read()
    if old != content:
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
    errs = sum(1 for i in issues if i.level == "ERROR")
    print(f"lessons index: {len(lessons)} lesson(s), {errs} error(s), "
          f"{len(issues) - errs} warning(s)"
          f"{'' if old == content else ' - INDEX.md updated'}")
    return 2 if issues else 0


def cmd_lint(root: str, lessons: list[Lesson], arts) -> int:
    issues = validate(root, lessons, arts) + ticket_lesson_issues(root, lessons, arts)
    for i in issues:
        print(i)
    if not issues:
        print(f"lessons lint: clean ({len(lessons)} lesson(s))")
    return 2 if issues else 0


def cmd_roles(root: str) -> int:
    cfg = forgecfg.load(root)
    print(f"scopes: {', '.join(cfg.lesson_scopes())}   ('{ALL}' addresses every scope)")
    print(f"roles:  {', '.join(ROLES)}   ('{ALL}' addresses every role)")
    print(f"budget: {cfg.lesson_budget} rule(s) per hand-off, "
          f"stale after {cfg.lesson_stale_days} days")
    for agent in cfg.agents:
        print(f"  {agent:<20} role {cfg.role_of_agent(agent)}, "
              f"scope {cfg.scope_of_agent(agent) or 'all'}")
    return 0


USAGE = __doc__


def main(argv: list[str]) -> int:
    args = list(argv[1:])
    root_arg = None
    if "--root" in args:
        i = args.index("--root")
        try:
            root_arg = args[i + 1]
        except IndexError:
            print("fatal: --root needs a path", file=sys.stderr)
            return 1
        del args[i:i + 2]
    if not args or args[0] in ("-h", "--help", "help"):
        print(USAGE)
        return 0 if args else 1

    root = agile.find_root(root_arg)
    cmd = args[0]
    if cmd == "roles":
        return cmd_roles(root)

    lessons, fatal = load_lessons(root)
    if fatal:
        for f in fatal:
            print(f"fatal: {f}", file=sys.stderr)
        return 1
    if cmd == "for":
        return cmd_for(root, lessons, args[1:])
    if cmd == "list":
        return cmd_list(root, lessons, args[1:])
    if cmd == "show":
        if len(args) < 2:
            print("fatal: show needs a lesson id", file=sys.stderr)
            return 1
        return cmd_show(root, lessons, args[1])
    if cmd == "retire":
        return cmd_retire(root, lessons, args[1:])
    if cmd == "supersede":
        return cmd_supersede(root, lessons, args[1:])

    arts, afatal = agile.load_all(root)
    if afatal:
        for f in afatal:
            print(f"fatal: {f}", file=sys.stderr)
        return 1
    if cmd == "new":
        return cmd_new(root, lessons, arts, args[1:])
    if cmd == "confirm":
        return cmd_confirm(root, lessons, arts, args[1:])
    if cmd == "audit":
        return cmd_audit(root, lessons, arts)
    if cmd == "index":
        return cmd_index(root, lessons, arts)
    if cmd == "lint":
        return cmd_lint(root, lessons, arts)
    print(f"fatal: unknown command '{cmd}'", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
