# frontmatter rewriting - the restricted grammar, one line per key
# --------------------------------------------------------------------------

def set_fields(path: str, values: dict) -> None:
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        raise SystemExit(f"fatal: {path} has no frontmatter")
    end = next(i for i, l in enumerate(lines[1:], 1) if l.strip() == "---")
    for key, val in values.items():
        if isinstance(val, list):
            rendered = f"{key}: [" + ", ".join(str(v) for v in val) + "]"
        elif val is None:
            rendered = f"{key}: null"
        else:
            rendered = f"{key}: {val}"
        for i in range(1, end):
            if lines[i].split(":", 1)[0].strip() == key:
                lines[i] = rendered
                break
        else:
            lines.insert(end, rendered)
            end += 1
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def append_to_section(path: str, heading: str, line: str) -> None:
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    m = re.search(r"^##\s+" + re.escape(heading) + r"\s*$", text, re.MULTILINE)
    if not m:
        return
    rest = text[m.end():]
    nxt = re.search(r"^##\s+", rest, re.MULTILINE)
    cut = m.end() + (nxt.start() if nxt else len(rest))
    chunk = text[m.end():cut].rstrip("\n")
    text = text[:m.end()] + chunk + "\n" + line + "\n\n" + text[cut:].lstrip("\n")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


